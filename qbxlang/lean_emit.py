"""Lower the kernel claims of an IR to a Lean file that Lean's kernel re-checks.

The emitted file imports `RequestProject.QBXCheck`, lists the claims as `QBX.Claim` values and
closes `checkAll cert = true` by `decide +kernel`; `checkAll_sound` then gives `c.Holds` for every
claim. So a Python result that is lowered here is accepted only if Lean independently agrees.
"""
import re


def _lean_list(xs, f=str):
    return "[" + ", ".join(f(x) for x in xs) + "]"


def _int(x):
    return f"({x})" if x < 0 else str(x)


def claim_to_lean(c):
    (k, v), = c.items()
    if k == "walkEnd":
        w, s, t = v
        return f".walkEnd {_lean_list(w, _int)} {s} {t}"
    if k == "parity":
        w, s, p = v
        return f".parity {_lean_list(w, _int)} {s} {p}"
    if k == "writhe":
        w, n = v
        return f".writhe {_lean_list(w, _int)} {_int(n)}"
    if k == "perm":
        n, w, p = v
        return f".perm {n} {_lean_list(w, _int)} {_lean_list(p)}"
    if k == "braidNe":
        a, b = v
        return f".braidNe {_lean_list(a, _int)} {_lean_list(b, _int)}"
    if k == "cellDist":
        x, y, d = v
        return f".cellDist {x} {y} {d}"
    if k == "gematria":
        m, ls, n = v
        return (f".gematria .{m} "
                + _lean_list(ls, lambda p: f"({p[0]}, {'true' if p[1] else 'false'})") + f" {n}")
    raise ValueError(f"unknown claim {k}")


def module_name(program):
    base = re.sub(r"\W", "_", program.rsplit("/", 1)[-1].rsplit(".", 1)[0])
    return "Cert_" + base


def emit(ir):
    claims = [(c["label"], c["kernel"]) for c in ir["checks"] if c["kernel"]]
    ns = module_name(ir["program"])
    body = ",\n".join(f"  -- {lab}\n  {claim_to_lean(k)}" for lab, k in claims)
    return f"""module

public import RequestProject.QBXCheck

/-! Generated by `python3 -m qbxlang lean {ir['program']}`.
{len(claims)} kernel claims; the Python results are accepted only if Lean re-checks them. -/

@[expose] public section

namespace QBXCert.{ns}

open QBX

/-- The kernel claims of `{ir['program']}`. -/
def cert : List Claim := [
{body}
]

/-- Lean's kernel re-checks every claim. -/
theorem cert_checks : checkAll cert = true := by decide +kernel

/-- Hence every claim holds (by `checkAll_sound`). -/
theorem cert_holds : ∀ c ∈ cert, c.Holds := checkAll_sound cert_checks

end QBXCert.{ns}
"""
