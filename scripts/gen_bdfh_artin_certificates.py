"""Generate the braid-move certificates and Lean files for the Artin groups of types
B3, B4, B5, D4, D5, D6, F4, H3, H4 (QBX/Formal/Streams/ArtinCerts/*.lean, QBX/Formal/Streams/Artin*.lean).

Same method as gen_e67_artin_certificates.py (constructive Matsumoto theorem), but with a
floating-point reflection representation so that non-crystallographic types (H3, H4) work too,
and with arbitrary braid exponents (checked by QBX.Formal.Streams.checkCodeGen).  The output is
only a hint: Lean re-checks every move.  Usage (from the repository root):
    python3 QBX/scripts/gen_bdfh_artin_certificates.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bdfh_core as C

ROOT = 'QBX/Formal/Streams'
SUB = {'B3':'B₃','B4':'B₄','B5':'B₅','D4':'D₄','D5':'D₅','D6':'D₆','F4':'F₄','H3':'H₃','H4':'H₄'}
MX = {'B3':'(CoxeterMatrix.Bₙ 3)','B4':'(CoxeterMatrix.Bₙ 4)','B5':'(CoxeterMatrix.Bₙ 5)',
      'D4':'coxD4','D5':'coxD5','D6':'coxD6','F4':'CoxeterMatrix.F₄','H3':'CoxeterMatrix.H₃',
      'H4':'CoxeterMatrix.H₄'}
WORD = {3:'three',4:'four',5:'five',6:'six',8:'eight',10:'ten',12:'twelve',15:'fifteen',30:'thirty'}
SUBDIGIT = str.maketrans('0123456789','₀₁₂₃₄₅₆₇₈₉')

def L(w): return "[" + ", ".join(map(str, w)) + "]"

def cert(t, n, name, u, v, mv, doc):
    return f'''
/-- Packed moves for `{name}`. -/
def {name}Code : ℕ :=
  {C.enc(mv)}

/-- {doc} -/
theorem {name} :
    checkCodeGen {t}Exp {n} {u} {v} {len(mv)}
      {name}Code = true := by
  decide +kernel
'''

def gen(TT):
    out = C.compute(TT)
    n, edges, A, B, half, eps = C.TYPES[TT]
    eps = eps or {}
    E = lambda s: eps.get(s, s)
    t = TT.lower(); sub = SUB[TT]; Mx = MX[TT]; h = 2 * half; npos = n * half
    g, cm = out['conj']
    D1 = tuple((A + B) * half)
    rest = "\n".join(f"  | {s} => {L(out[s][0])}" for s in range(n - 1)) + f"\n  | _ => {L(out[n-1][0])}"
    es = "[" + ", ".join(f"({a}, {b}, {k})" for a, b, k in edges) + "]"
    body = f'''module

public import QBX.Formal.Streams.ArtinCertGen

@[expose] public section

/-!
# Words and braid-move certificates for the `{sub}` Artin group

* `{t}Exp`: the Coxeter exponents of `{sub}` (weighted edges `{es}`);
* `{t}WordA = {L(A)}`, `{t}WordB = {L(B)}`: the two colour classes of the diagram;
* `{t}DeltaWordAB = (AB)^{half}` ({npos} letters, the number of positive roots of `{sub}`);
* `{t}RestWord s`: a word `X` with `Δ = σₛ X = X σ_{{ε s}}`, where `ε` is
  {"the diagram automorphism " + ", ".join(f"`{a} ↔ {b}`" for a, b in eps.items() if a < b) if eps else "the identity"};
* `{t}ConjWord`, `{t}StdWord`: a conjugating word and the standard Coxeter word.

Machine-generated by `QBX/scripts/gen_bdfh_artin_certificates.py` (see
`QBX.Formal.Streams.checkCodeGen`): each number packs the moves, one base-`2^13` digit
`p * 64 + i * 8 + j` per move, and each theorem checks in the kernel that applying them transforms
the first word into the second.
-/

namespace QBX.Formal.Streams

/-- The Coxeter exponents of `{sub}` on natural-number indices. -/
def {t}Exp : ℕ → ℕ → ℕ := coxExpOf {es}

/-- First colour class of the `{sub}` diagram. -/
def {t}WordA : List ℕ := {L(A)}

/-- Second colour class of the `{sub}` diagram. -/
def {t}WordB : List ℕ := {L(B)}

/-- `(AB)^{half}`. -/
def {t}DeltaWordAB : List ℕ := (List.replicate {half} ({t}WordA ++ {t}WordB)).flatten

/-- `(BA)^{half}`. -/
def {t}DeltaWordBA : List ℕ := (List.replicate {half} ({t}WordB ++ {t}WordA)).flatten

/-- A word `X` with `Δ = σₛ X = X σ_{{ε s}}`. -/
def {t}RestWord : ℕ → List ℕ
{rest}

/-- A word `g` with `c_bip · g = g · c_std` (commutation moves only). -/
def {t}ConjWord : List ℕ := {L(g)}

/-- The standard-order Coxeter word `[0, 1, …, {n-1}]`. -/
def {t}StdWord : List ℕ := {L(list(range(n)))}
'''
    C.check(D1, tuple((B + A) * half), out['ab'])
    body += cert(t, n, f"{t}Cert_AB", f"{t}DeltaWordAB", f"{t}DeltaWordBA", out['ab'],
                 f"`(AB)^{half} = (BA)^{half}`.")
    C.check(tuple(A + B + g), tuple(g + list(range(n))), cm)
    body += cert(t, n, f"{t}Cert_cox", f"({t}WordA ++ {t}WordB ++ {t}ConjWord)",
                 f"({t}ConjWord ++ {t}StdWord)", cm,
                 "`c_bip · g` and `g · c_std` are related by commutation moves.")
    for s in range(n):
        X, m1, m2 = out[s]
        C.check(D1, (s,) + X, m1); C.check(D1, X + (E(s),), m2)
        body += cert(t, n, f"{t}Cert_left{s}", f"{t}DeltaWordAB", f"({s} :: {t}RestWord {s})", m1,
                     f"`Δ = σ{s} X`.")
        body += cert(t, n, f"{t}Cert_right{s}", f"{t}DeltaWordAB", f"({t}RestWord {s} ++ [{E(s)}])",
                     m2, f"`Δ = X σ{E(s)}`.")
    body += "\nend QBX.Formal.Streams\n"
    os.makedirs(f"{ROOT}/ArtinCerts", exist_ok=True)
    open(f"{ROOT}/ArtinCerts/{TT}.lean", "w").write(body)

    twisted = bool(eps)
    TW = f"{t}Twist s" if twisted else "s"
    cases = "\n".join(f"  · exact ⟨{t}Lift_eq {t}Cert_left{s}, {t}Lift_eq {t}Cert_right{s}⟩" for s in range(n))
    std_prod = " * ".join(f"σ {i}" for i in range(n))
    nmoves = len(out['ab']) + len(cm) + sum(len(out[s][1]) + len(out[s][2]) for s in range(n))
    hw = WORD[h]; halfw = WORD[half]
    extra_import = "public import QBX.Formal.Streams.CoxeterD\n" if TT.startswith('D') else ""
    if twisted:
        twl = [E(s) for s in range(n)]
        twist_defs = f'''
/-- The diagram automorphism `ε` of `{sub}`: {", ".join(f"`{a} ↔ {b}`" for a, b in eps.items() if a < b)}. -/
def {t}Twist : Fin {n} → Fin {n} := ![{", ".join(map(str, twl))}]

theorem {t}Twist_twist (s : Fin {n}) : {t}Twist ({t}Twist s) = s := by
  revert s; decide

/-- `ε` is an automorphism of the Coxeter matrix. -/
theorem {t}Twist_exp : ∀ i j : Fin {n}, {Mx} ({t}Twist i) ({t}Twist j) = {Mx} i j := by decide
'''
        a0 = [a for a, b in eps.items() if a < b][0]
        central_part = f'''
/-- **`σₛ Δ = Δ σ_{{ε s}}`**: conjugation by `Δ` is the diagram automorphism. -/
theorem σ_mul_{t}Delta (s : Fin {n}) : σ s * {t}Delta = {t}Delta * σ ({t}Twist s) := by
  conv_lhs => rw [{t}Delta_eq_mul_gen s]
  rw [← mul_assoc, ← {t}Delta_eq_gen_mul s]

/-- The simple-reflection matrices of `{sub}` satisfy the Coxeter relations. -/
theorem {t}_isLiftable : {Mx}.IsLiftable (simpleRefl {Mx}) := by
  unfold CoxeterMatrix.IsLiftable
  decide +kernel

/-- **`Δ` is not central** in the `{sub}` Artin group: `σ{a0} Δ ≠ Δ σ{a0}`. -/
theorem {t}Delta_not_central : σ {a0} * {t}Delta ≠ {t}Delta * σ {a0} :=
  not_comm_of_twist {t}_isLiftable (σ_mul_{t}Delta {a0}) (by decide)

/-- Every generator commutes with `Δ²`. -/
theorem σ_mul_{t}Delta_sq (s : Fin {n}) : σ s * {t}Delta ^ 2 = {t}Delta ^ 2 * σ s := by
  rw [pow_two, ← mul_assoc, σ_mul_{t}Delta, mul_assoc, σ_mul_{t}Delta, {t}Twist_twist, mul_assoc]

/-- **`Δ²` is central in the `{sub}` Artin group.** -/
theorem {t}Delta_sq_central (x : Artin{TT}) : {t}Delta ^ 2 * x = x * {t}Delta ^ 2 :=
  central_of_forall_σ σ_mul_{t}Delta_sq x
'''
        doc_central = f'''* `σ_mul_{t}Delta`: `σₛ Δ = Δ σ_{{ε s}}` with `ε` the diagram automorphism; `{t}Delta_not_central`:
  **`Δ` is not central**; `{t}Delta_sq_central`: `Δ²` is central;'''
    else:
        twist_defs = ""
        central_part = f'''
/-- Every generator commutes with `Δ`. -/
theorem σ_mul_{t}Delta (s : Fin {n}) : σ s * {t}Delta = {t}Delta * σ s := by
  conv_lhs => rw [{t}Delta_eq_mul_gen s]
  rw [← mul_assoc, ← {t}Delta_eq_gen_mul s]

/-- **`Δ` is central in the `{sub}` Artin group.** -/
theorem {t}Delta_central (x : Artin{TT}) : {t}Delta * x = x * {t}Delta :=
  central_of_forall_σ σ_mul_{t}Delta x

/-- `Δ²` is central. -/
theorem {t}Delta_sq_central (x : Artin{TT}) : {t}Delta ^ 2 * x = x * {t}Delta ^ 2 := by
  rw [pow_two, mul_assoc, {t}Delta_central, ← mul_assoc, {t}Delta_central, mul_assoc]
'''
        doc_central = f"* `{t}Delta_central`: **`Δ` is central**;"
    main = f'''module

public import QBX.Formal.Streams.ArtinCerts.{TT}
{extra_import}
@[expose] public section

/-!
# The `{sub}` Artin group: the Garside element `Δ` and `c^{h} = Δ²`

`Artin{TT}` is the Artin group of `{Mx.strip("()")}`.  With the colour classes `A = {L(A)}`,
`B = {L(B)}`, `a = ∏_{{i ∈ A}} σᵢ`, `b = ∏_{{i ∈ B}} σᵢ` and the bipartite Coxeter element `c = ab`:

  `Δ = (ab)^{half}`   ({npos} letters, the number of positive roots of `{sub}`).

Main results:

* `{t}Delta_eq_ba`: `(ab)^{half} = (ba)^{half}`;
* `{t}Delta_eq_gen_mul`, `{t}Delta_eq_mul_gen`: `Δ = σₛ Xₛ = Xₛ σ_{{ε s}}` for every generator;
{doc_central}
* `{t}CoxBip_pow_{halfw}`, `{t}CoxBip_pow_{hw}`: `c^{half} = Δ` and **`c^{h} = Δ²`** (`{h}` is the Coxeter
  number of `{sub}`);
* `{t}CoxStd_pow_{hw}`: the same for the standard Coxeter element `σ₀σ₁⋯σ{str(n-1).translate(SUBDIGIT)}`;
* `{t}_pow_{hw}_rotate`: cyclic rotations of a word preserve `p^{h} = Δ²`;
* `{t}Delta_degree`, `{t}Delta_pow_ne_one`: `Δ` has degree {npos} and infinite order.

The word identities are kernel-checked braid-move certificates (`ArtinCerts/{TT}.lean`,
{nmoves} moves in total).
-/

namespace QBX.Formal.Streams

open ArtinGroup

/-- The Artin group of type `{sub}`. -/
abbrev Artin{TT} := ArtinGroup {Mx}

theorem {t}Exp_eq : ∀ i j : Fin {n}, {t}Exp i j = {Mx} i j := by decide

theorem {t}Lift_eq {{u v : List ℕ}} {{k c : ℕ}} (h : checkCodeGen {t}Exp {n} u v k c = true) :
    natLift {Mx} u = natLift {Mx} v :=
  natLift_eq_gen {t}Exp_eq h
{twist_defs}
/-- The bipartite Coxeter element `c = ab`. -/
def {t}CoxBip : Artin{TT} := natLift {Mx} ({t}WordA ++ {t}WordB)

/-- The Garside element `Δ = (ab)^{half}`. -/
def {t}Delta : Artin{TT} := natLift {Mx} {t}DeltaWordAB

/-- **`c^{half} = Δ`.** -/
theorem {t}CoxBip_pow_{halfw} : {t}CoxBip ^ {half} = {t}Delta :=
  (natLift_replicate _ {half}).symm

/-- `Δ = (ab)^{half} = (ba)^{half}`. -/
theorem {t}Delta_eq_ba : {t}Delta = natLift {Mx} {t}DeltaWordBA :=
  {t}Lift_eq {t}Cert_AB

theorem {t}Delta_words (s : Fin {n}) :
    {t}Delta = natLift {Mx} ((s : ℕ) :: {t}RestWord s) ∧
      {t}Delta = natLift {Mx} ({t}RestWord s ++ [(({TW} : Fin {n}) : ℕ)]) := by
  fin_cases s
{cases}

/-- Every generator left-divides `Δ`: `Δ = σₛ Xₛ`. -/
theorem {t}Delta_eq_gen_mul (s : Fin {n}) :
    {t}Delta = σ s * natLift {Mx} ({t}RestWord s) := by
  rw [({t}Delta_words s).1, natLift_cons, natGen_fin]

/-- The same cofactor right-divides `Δ`: `Δ = Xₛ σ_{{ε s}}`. -/
theorem {t}Delta_eq_mul_gen (s : Fin {n}) :
    {t}Delta = natLift {Mx} ({t}RestWord s) * σ ({TW}) := by
  rw [({t}Delta_words s).2, natLift_append, natLift_singleton, natGen_fin]
{central_part}
/-- **`c^{h} = Δ²`** for the bipartite Coxeter element (`{h}` = Coxeter number of `{sub}`). -/
theorem {t}CoxBip_pow_{hw} : {t}CoxBip ^ {h} = {t}Delta ^ 2 := by
  rw [show ({h} : ℕ) = {half} * 2 by rfl, pow_mul, {t}CoxBip_pow_{halfw}]

/-- Cyclic rotation of a word preserves `p^{h} = Δ²`. -/
theorem {t}_pow_{hw}_rotate (x : ℕ) (r : List ℕ)
    (h : natLift {Mx} (x :: r) ^ {h} = {t}Delta ^ 2) :
    natLift {Mx} (r ++ [x]) ^ {h} = {t}Delta ^ 2 :=
  natLift_pow_rotate {t}Delta_sq_central {h} x r h

/-- The standard-order Coxeter element `σ₀σ₁⋯σ{str(n-1).translate(SUBDIGIT)}`. -/
def {t}CoxStd : Artin{TT} := natLift {Mx} {t}StdWord

theorem {t}CoxStd_eq : {t}CoxStd = {std_prod} := by
  simp only [{t}CoxStd, natLift, {t}StdWord, List.map_cons, List.map_nil, List.prod_cons,
    List.prod_nil, mul_one, mul_assoc]
  simp only [natGen, Nat.lt_succ_self, dite_true]
  rfl

/-- **`(σ₀σ₁⋯σ{str(n-1).translate(SUBDIGIT)})^{h} = Δ²`.** -/
theorem {t}CoxStd_pow_{hw} : {t}CoxStd ^ {h} = {t}Delta ^ 2 := by
  set g := natLift {Mx} {t}ConjWord
  have hs : SemiconjBy g {t}CoxStd {t}CoxBip := by
    have := {t}Lift_eq {t}Cert_cox
    rw [natLift_append, natLift_append] at this
    exact this.symm
  have hh := (hs.pow_right {h}).eq
  rw [{t}CoxBip_pow_{hw}, {t}Delta_sq_central] at hh
  exact mul_left_cancel hh

/-- `Δ` has degree {npos} (the number of positive roots of `{sub}`). -/
theorem {t}Delta_degree : degree {t}Delta = Multiplicative.ofAdd ({npos} : ℤ) := by
  rw [{t}Delta, natLift_degree _ (by decide)]
  rfl

/-- `Δ` has infinite order. -/
theorem {t}Delta_pow_ne_one {{k : ℕ}} (hk : k ≠ 0) : {t}Delta ^ k ≠ 1 := by
  intro h
  have := congrArg degree h
  rw [map_pow, {t}Delta_degree, map_one, ← ofAdd_nsmul, ← ofAdd_zero] at this
  have := Multiplicative.ofAdd.injective this
  simp only [nsmul_eq_mul] at this
  omega

end QBX.Formal.Streams
'''
    open(f"{ROOT}/Artin{TT}.lean", "w").write(main)
    print(TT, nmoves)

if __name__ == '__main__':
    for TT in (sys.argv[1:] or list(C.TYPES)):
        gen(TT)
