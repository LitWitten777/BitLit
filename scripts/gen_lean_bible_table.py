#!/usr/bin/env python3
"""
Regenerate Formal/BibleBraidGenesis1.lean: the Python braid words of every verse of the bundled
Genesis 1 corpus (8 and 23 strands, sofit rule on and off), for the Lean cross-check theorem.
Each verse becomes its own small kernel certificate (see the module docstring of the output).

    cd QBX && python3 scripts/gen_lean_bible_table.py
"""
import os
import sys
import unicodedata

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from qbx_bible import Encoding, encode_text, load_corpus  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Formal", "BibleBraidGenesis1.lean")


def lean_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lean_list(xs) -> str:
    return "[" + ", ".join(str(x) for x in xs) + "]"


def lean_char(c: str) -> str:
    """A Lean character literal; combining marks and other non-letters are escaped."""
    o = ord(c)
    if c.isalpha() and not unicodedata.combining(c):
        return f"'{c}'"
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    if o <= 0xFFFF and (unicodedata.combining(c) or unicodedata.category(c)[0] in "MZPCS"):
        return f"'\\u{o:04x}'"
    return f"'{c}'"


def lean_chars(s: str) -> str:
    return "[" + ", ".join(lean_char(c) for c in s) + "]"


def main() -> None:
    verses = load_corpus()
    blocks = []
    names = []
    for k, v in enumerate(verses, start=1):
        words = {key: encode_text(v.text, v.ref, Encoding(n, sofit)).braid.short_form()
                 for key, (n, sofit) in {"w8": (8, True), "w8off": (8, False),
                                         "w23": (23, True)}.items()}
        name = f"gen1_{k}"
        names.append(name)
        blocks.append(f"""/-- {v.ref}. -/
def {name} : VerseRecord :=
  ⟨{lean_str(v.ref)}, {lean_str(v.text)},
    {lean_list(words['w8'])},
    {lean_list(words['w8off'])},
    {lean_list(words['w23'])}⟩

/-- The characters of {v.ref}. -/
def {name}_chars : List Char :=
  {lean_chars(v.text)}

theorem {name}_text : {name}.text = String.ofList {name}_chars := by decide +kernel

theorem {name}_fast : {name}.checkFast {name}_chars = true := by decide +kernel

theorem {name}_agrees : {name}.Agrees := {name}.agrees_of {name}_text {name}_fast
""")
    body = "\n".join(blocks)
    table = ", ".join(names)
    agrees = ",\n    ".join(f"{n}_agrees" for n in names)
    text = f'''module

public import QBX.Formal.BibleBraidFast

@[expose] public section

/-!
# Genesis 1: the Lean model agrees with the Python implementation

Generated by `QBX/scripts/gen_lean_bible_table.py` from `QBX/data/bible/genesis_1_wlc.tsv`:
for each of the 31 verses, the pointed text and the braid words that `qbx_bible` outputs on
8 strands (sofit rule on and off) and on 23 strands (sofit rule on).

`genesis_1_model_agrees_with_python` checks that the Lean model `QBX.Formal.Bible.convert`
produces exactly these words for every verse.

**How the check is organised (scaled out).**  Checking the whole table in one kernel
evaluation, as an earlier version of this file did, needed more than 40 GB of memory.  Now
every verse is its own certificate, made of two small kernel evaluations:

* `gen1_k_text`: the verse string is `String.ofList` of an explicit character list.  This
  direction (encoding characters) is several times cheaper for the kernel than decoding the
  string with `String.toList`;
* `gen1_k_fast`: the braid words, computed with the arithmetic classifier `convertFast`, which
  `convertFast_eq` proves equal to `convert`.

`VerseRecord.agrees_of` turns the two into the statement about `convert` and `String.toList`,
and the final theorem collects the 31 verse certificates.  Each certificate is checked
independently (and can be checked in parallel).
-/

namespace QBX.Formal.Bible

/-- One verse with the words the Python implementation outputs. -/
structure VerseRecord where
  ref : String
  text : String
  word8 : List ℤ
  word8NoSofit : List ℤ
  word23 : List ℤ

/-- The cross-check of one verse given its characters, as a boolean. -/
def VerseRecord.checkChars (v : VerseRecord) (cs : List Char) : Bool :=
  shortForm (convert 6 true cs) == v.word8 &&
  shortForm (convert 6 false cs) == v.word8NoSofit &&
  shortForm (convert 21 true cs) == v.word23

/-- The cross-check of one verse, as a boolean. -/
def VerseRecord.check (v : VerseRecord) : Bool := v.checkChars v.text.toList

/-- The same check computed with the fast classifier. -/
def VerseRecord.checkFast (v : VerseRecord) (cs : List Char) : Bool :=
  shortForm (convertFast 6 true cs) == v.word8 &&
  shortForm (convertFast 6 false cs) == v.word8NoSofit &&
  shortForm (convertFast 21 true cs) == v.word23

/-- The model gives the Python words for this verse. -/
def VerseRecord.Agrees (v : VerseRecord) : Prop :=
  shortForm (convert 6 true v.text.toList) = v.word8 ∧
    shortForm (convert 6 false v.text.toList) = v.word8NoSofit ∧
    shortForm (convert 21 true v.text.toList) = v.word23

/-- A verse certificate: an explicit character list for the text and the fast check. -/
theorem VerseRecord.agrees_of (v : VerseRecord) {{cs : List Char}}
    (ht : v.text = String.ofList cs) (hc : v.checkFast cs = true) : v.Agrees := by
  simp only [VerseRecord.checkFast, convertFast_eq, Bool.and_eq_true, beq_iff_eq] at hc
  simp only [VerseRecord.Agrees, ht, String.toList_ofList]
  exact ⟨hc.1.1, hc.1.2, hc.2⟩

{body}
/-- Genesis 1 (Westminster Leningrad Codex) with the Python braid words. -/
def genesis1Table : List VerseRecord := [{table}]

theorem genesis1Table_agrees : ∀ v ∈ genesis1Table, v.Agrees := by
  simp only [genesis1Table, List.forall_mem_cons, List.not_mem_nil, IsEmpty.forall_iff,
    implies_true, and_true]
  exact ⟨{agrees}⟩

/-- **Model = implementation on Genesis 1.**  For every verse of Genesis 1 the Lean conversion
gives exactly the braid words of the Python implementation, on 8 strands with and without the
sofit rule and on 23 strands. -/
theorem genesis_1_model_agrees_with_python : genesis1Table.length = 31 ∧
    ∀ v ∈ genesis1Table, shortForm (convert 6 true v.text.toList) = v.word8 ∧
      shortForm (convert 6 false v.text.toList) = v.word8NoSofit ∧
      shortForm (convert 21 true v.text.toList) = v.word23 :=
  ⟨rfl, genesis1Table_agrees⟩

theorem genesis1Table_check : genesis1Table.all VerseRecord.check = true := by
  rw [List.all_eq_true]
  intro v hv
  obtain ⟨h1, h2, h3⟩ := genesis1Table_agrees v hv
  simp [VerseRecord.check, VerseRecord.checkChars, h1, h2, h3]

end QBX.Formal.Bible
'''
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
