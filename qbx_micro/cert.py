LEAN_HEADER = """module

/-!
# Cayley-Dickson law certificates (generated)

Generated by `QBX/src/qbx_micro/cert.py` (`python3 -m qbx_micro certs`); do not edit by hand.

Each theorem says that a law of the library in `qbx_micro/laws.py` fails in an integral
model of one Cayley-Dickson algebra: level 2 (quaternions H), 3 (octonions O),
4 (sedenions S).  The statements use only core Lean (`List Int`, no Mathlib) and are closed by
`decide`, i.e. by evaluating both sides in the kernel, so the same witness can be re-checked in
any proof assistant (the generator also writes Coq and Isabelle versions, which are not run
here).

The model: vectors of length `2 ^ n` with the doubling product
`(a, b)(c, d) = (a c - conj d b, d a + b conj c)`.  These are failure certificates only; that a
law *holds* at a lower level is not claimed in this file.
-/

@[expose] public section
"""


def law_certificate_items(levels=(2, 3, 4), budget=4096):
    items = []
    for name, eq in laws.LAWS:
        for L in levels:
            st, w = laws.check(eq, L, budget)
            if st == "fails":
                thm = "%s_fails_%s" % (name.replace("-", "_"), laws.NAMES[L])
                items.append((thm, eq, L, w, None))
    return items


def zero_divisor_theorem(level=4):
    a, b = laws.find_zero_divisor(level)
    return ("/-- The level-%d algebra (%s) has zero divisors: a nonzero `a` and `b` with "
            "`a b = 0`. -/\ntheorem zero_divisor_%s :\n    %s ≠ scalar %d 0 ∧ %s ≠ scalar %d 0 ∧\n"
            "    mul %d %s %s = scalar %d 0 := by\n  decide\n") % (
        level, laws.NAMES[level], laws.NAMES[level], _lean_list(a), level, _lean_list(b), level,
        level, _lean_list(a), _lean_list(b), level)


def lean_law_file():
    body = lean_file("QBX.Formal.Certificates.CayleyDickson", law_certificate_items(),
                     header=LEAN_HEADER)
    return body.replace("\nend QBX.Formal.Certificates.CayleyDickson",
                        "\n" + zero_divisor_theorem() + "\nend QBX.Formal.Certificates.CayleyDickson"
                        ) + "\nend\n"
