"""Prover-neutral certificates for the facts `laws.py` can decide by evaluation.

A failed identity comes with an integer witness.  Checking the witness only
needs the doubling product and integer arithmetic, so the same certificate is
written out for several proof assistants.  Each certificate is
self-contained: it defines the Cayley-Dickson product itself and asks the
prover's kernel to evaluate both sides.

  lean   Lean 4 core only (no Mathlib), closed by `decide`
  coq    Coq / Rocq with ZArith and List, closed by `vm_compute` + `discriminate`
  isa    Isabelle/HOL, closed by `eval`

Only the Lean form is machine-checked inside this repository (the files under
`QBX/Formal/Certificates/` are generated by `lean_file` and built with the
library).  The Coq and Isabelle texts follow the same definitions but have not
been run here.

A certificate shows "this identity fails in this integral model".  Positive
claims ("the identity holds") are never produced here: those need a proof.
"""

from . import laws


def _lean_expr(node, level, env):
    tag = node[0]
    if tag == "var":
        return _lean_list(env[node[1]])
    if tag == "num":
        return "(scalar %d %d)" % (level, node[1])
    if tag == "neg":
        return "(neg %s)" % _lean_expr(node[1], level, env)
    if tag == "conj":
        return "(conj %d %s)" % (level, _lean_expr(node[1], level, env))
    op = {"+": "add", "-": "sub", "*": "mul %d" % level}[tag]
    return "(%s %s %s)" % (op, _lean_expr(node[1], level, env), _lean_expr(node[2], level, env))


def _lean_list(v):
    return "[" + ", ".join(str(x) for x in v) + "]"


LEAN_PRELUDE = """/-- Integer vectors of length `2 ^ n`; `n` is the Cayley-Dickson level. -/
def neg (x : List Int) : List Int := x.map (fun v => -v)
def add (x y : List Int) : List Int := List.zipWith (fun a b => a + b) x y
def sub (x y : List Int) : List Int := List.zipWith (fun a b => a - b) x y
/-- Conjugation: `conj (a, b) = (conj a, -b)`. -/
def conj : Nat → List Int → List Int
  | 0, x => x
  | n + 1, x => conj n (x.take (2 ^ n)) ++ neg (x.drop (2 ^ n))
/-- The doubling product `(a, b)(c, d) = (a c - conj d b, d a + b conj c)`. -/
def mul : Nat → List Int → List Int → List Int
  | 0, x, y => [x.headD 0 * y.headD 0]
  | n + 1, x, y =>
    let a := x.take (2 ^ n); let b := x.drop (2 ^ n)
    let c := y.take (2 ^ n); let d := y.drop (2 ^ n)
    sub (mul n a c) (mul n (conj n d) b) ++ add (mul n d a) (mul n b (conj n c))
/-- The integer `k` as an element of level `n`. -/
def scalar (n : Nat) (k : Int) : List Int := k :: List.replicate (2 ^ n - 1) 0
"""


def lean_theorem(name, identity, level, witness, doc=None):
    lhs, rhs = laws.parse(identity)
    wit = ", ".join("%s = %s" % (v, _lean_list(witness[v])) for v in sorted(witness))
    doc = doc or "The identity `%s` fails in the level-%d algebra (%s)." % (
        identity, level, laws.NAMES[level])
    doc += " Witness: %s." % wit
    return "/-- %s -/\ntheorem %s :\n    %s ≠\n    %s := by\n  decide\n" % (
        doc, name, _lean_expr(lhs, level, witness), _lean_expr(rhs, level, witness))


def lean_file(namespace, items, header=""):
    """`items`: list of (theorem name, identity, level, witness, docstring)."""
    body = "\n".join(lean_theorem(*it) for it in items)
    return "%s\nnamespace %s\n\n%s\n%s\nend %s\n" % (header, namespace, LEAN_PRELUDE, body, namespace)


def _coq_expr(node, level):
    tag = node[0]
    if tag == "var":
        return node[1]
    if tag == "num":
        return "(scalar %d %d)" % (level, node[1])
    if tag == "neg":
        return "(vneg %s)" % _coq_expr(node[1], level)
    if tag == "conj":
        return "(conj %d %s)" % (level, _coq_expr(node[1], level))
    op = {"+": "vadd", "-": "vsub", "*": "mul %d" % level}[tag]
    return "(%s %s %s)" % (op, _coq_expr(node[1], level), _coq_expr(node[2], level))


COQ_PRELUDE = """Require Import ZArith List. Import ListNotations. Open Scope Z_scope.
Definition vneg (x : list Z) := map Z.opp x.
Fixpoint vadd (x y : list Z) := match x, y with a :: x', b :: y' => (a + b) :: vadd x' y' | _, _ => [] end.
Fixpoint vsub (x y : list Z) := match x, y with a :: x', b :: y' => (a - b) :: vsub x' y' | _, _ => [] end.
Fixpoint conj (n : nat) (x : list Z) : list Z :=
  match n with O => x | S m => conj m (firstn (2 ^ m) x) ++ vneg (skipn (2 ^ m) x) end.
Fixpoint mul (n : nat) (x y : list Z) : list Z :=
  match n with
  | O => [hd 0 x * hd 0 y]
  | S m => let a := firstn (2 ^ m) x in let b := skipn (2 ^ m) x in
           let c := firstn (2 ^ m) y in let d := skipn (2 ^ m) y in
           vsub (mul m a c) (mul m (conj m d) b) ++ vadd (mul m d a) (mul m b (conj m c))
  end.
Definition scalar (n : nat) (k : Z) := k :: repeat 0 (2 ^ n - 1).
"""


def coq_lemma(name, identity, level, witness):
    lhs, rhs = laws.parse(identity)
    lets = "".join("let %s := [%s] in " % (v, "; ".join(str(x) for x in witness[v]))
                   for v in sorted(witness))
    return "Lemma %s : %s%s <> %s.\nProof. vm_compute. discriminate. Qed.\n" % (
        name, lets, _coq_expr(lhs, level), _coq_expr(rhs, level))


ISA_PRELUDE = """theory Certificate imports Main begin
definition vneg :: "int list \\<Rightarrow> int list" where "vneg x = map uminus x"
definition vadd :: "int list \\<Rightarrow> int list \\<Rightarrow> int list" where "vadd x y = map2 (+) x y"
definition vsub :: "int list \\<Rightarrow> int list \\<Rightarrow> int list" where "vsub x y = map2 (-) x y"
fun conj :: "nat \\<Rightarrow> int list \\<Rightarrow> int list" where
  "conj 0 x = x"
| "conj (Suc m) x = conj m (take (2 ^ m) x) @ vneg (drop (2 ^ m) x)"
fun mul :: "nat \\<Rightarrow> int list \\<Rightarrow> int list \\<Rightarrow> int list" where
  "mul 0 x y = [hd (x @ [0]) * hd (y @ [0])]"
| "mul (Suc m) x y = (let a = take (2 ^ m) x; b = drop (2 ^ m) x; c = take (2 ^ m) y; d = drop (2 ^ m) y
     in vsub (mul m a c) (mul m (conj m d) b) @ vadd (mul m d a) (mul m b (conj m c)))"
definition scalar :: "nat \\<Rightarrow> int \\<Rightarrow> int list" where "scalar n k = k # replicate (2 ^ n - 1) 0"
"""


def isa_lemma(name, identity, level, witness):
    lhs, rhs = laws.parse(identity)
    lets = "".join("let %s = [%s] in " % (v, ", ".join(str(x) for x in witness[v]))
                   for v in sorted(witness))
    return 'lemma %s: "%s%s \\<noteq> %s" by eval\n' % (
        name, lets, _coq_expr(lhs, level), _coq_expr(rhs, level))


def all_formats(name, identity, level, witness):
    """{format: certificate text} for one failed identity."""
    return {
        "lean": lean_file("QBXCert", [(name, identity, level, witness, None)]),
        "coq": COQ_PRELUDE + "\n" + coq_lemma(name, identity, level, witness),
        "isa": ISA_PRELUDE + "\n" + isa_lemma(name, identity, level, witness) + "end\n",
    }


